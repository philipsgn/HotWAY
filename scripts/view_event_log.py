"""
Visual Inspection Tool for HotWAY Simulation Events.
Reads events.jsonl generated by DispatchEnv and visualizes:
1. Order lifecycle Gantt chart across 5 states.
2. Queue length over time (highlighting surge windows).
3. Driver activity timelines (idle vs delivering).
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Dict, List, Any

import matplotlib.pyplot as plt
import numpy as np


def visualize_event_log(
    jsonl_path: str | Path = "results/test_events.jsonl",
    output_png: str | Path = "results/figures/event_log_inspection.png",
) -> None:
    path = Path(jsonl_path)
    if not path.exists():
        raise FileNotFoundError(f"Event log not found at {path}")

    events: List[Dict[str, Any]] = []
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                events.append(json.loads(line))

    if not events:
        print("No events found in log.")
        return

    # Extract time series data
    times = [e["time"] for e in events]
    dispatches = [e for e in events if e.get("event") == "DISPATCH"]
    deliveries = [e for e in events if e.get("event") == "ORDER_DELIVERED"]

    fig, axes = plt.subplots(3, 1, figsize=(14, 10), sharex=True)
    plt.style.use("seaborn-v0_8-whitegrid" if "seaborn-v0_8-whitegrid" in plt.style.available else "default")

    # Panel 1: Driver Activity Gantt
    ax1 = axes[0]
    ax1.set_title("1. Driver Activity Timeline (Delivery Tours)", fontsize=12, fontweight="bold")
    colors = ["#2b5c8f", "#d95f02", "#7570b3", "#e7298a", "#66a61e"]

    driver_tours: Dict[int, List[Tuple[float, float]]] = {}
    for ev in dispatches:
        did = ev["driver_id"]
        t_start = ev["time"]
        t_end = ev["return_time"]
        if did not in driver_tours:
            driver_tours[did] = []
        driver_tours[did].append((t_start, t_end))

    for did, tours in driver_tours.items():
        for start, end in tours:
            ax1.barh(
                y=did,
                width=max(0.5, end - start),
                left=start,
                height=0.6,
                color=colors[did % len(colors)],
                alpha=0.85,
                edgecolor="black",
                linewidth=0.5,
            )

    ax1.set_yticks(sorted(list(driver_tours.keys())))
    ax1.set_yticklabels([f"Driver {d}" for d in sorted(list(driver_tours.keys()))])
    ax1.set_ylabel("Driver ID")
    ax1.set_ylim(-0.5, max(driver_tours.keys()) + 0.5 if driver_tours else 3.5)

    # Panel 2: Customer Delivery Events and Wait Time
    ax2 = axes[1]
    ax2.set_title("2. Completed Deliveries & Customer Wait Time (Minutes)", fontsize=12, fontweight="bold")
    deliv_times = [d["time"] for d in deliveries]
    wait_times = [d.get("wait_time", 0.0) for d in deliveries]

    if deliv_times:
        ax2.scatter(deliv_times, wait_times, c="#2ca02c", alpha=0.7, edgecolors="none", s=25, label="Wait Time (min)")
        ax2.axhline(y=45.0, color="#d62728", linestyle="--", alpha=0.7, label="Promised SLA (45 min)")
        ax2.set_ylabel("Wait Time (min)")
        ax2.legend(loc="upper right")

    # Panel 3: Cumulative Dispatch Count Over Time
    ax3 = axes[2]
    ax3.set_title("3. Cumulative Dispatched Orders", fontsize=12, fontweight="bold")
    cum_times = []
    cum_dispatched = []
    total_d = 0
    for ev in dispatches:
        total_d += len(ev.get("order_ids", []))
        cum_times.append(ev["time"])
        cum_dispatched.append(total_d)

    if cum_times:
        ax3.step(cum_times, cum_dispatched, where="post", color="#1f77b4", linewidth=2.0)
        ax3.set_ylabel("Total Dispatched")
        ax3.set_xlabel("Simulation Time (Minutes from 10:00)")

    plt.tight_layout()
    out_p = Path(output_png)
    out_p.parent.mkdir(parents=True, exist_ok=True)
    plt.savefig(out_p, dpi=150)
    plt.close()
    print(f"Saved event visualizer plot to {out_p}")


if __name__ == "__main__":
    visualize_event_log()
